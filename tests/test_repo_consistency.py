"""Static consistency tests: workflow, docs, scripts and results.

These guard the .NET-only setup assumptions shared across the workflow,
local runner scripts, result generation and documentation.
"""

import glob
import os
import re
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

WORKFLOW = os.path.join(REPO_ROOT, ".github", "workflows", "benchmark.yml")
README = os.path.join(REPO_ROOT, "README.md")
BENCHMARK_SH = os.path.join(REPO_ROOT, "k6", "benchmark.sh")
GENERATE_RESULTS = os.path.join(REPO_ROOT, "k6", "generate-results.py")
BUILD_MATRIX = os.path.join(REPO_ROOT, "k6", "build-matrix.py")

def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


class WorkflowTests(unittest.TestCase):
    def setUp(self):
        self.workflow = read(WORKFLOW)

    def test_dedicated_runner_group(self):
        self.assertIn("group: benchmark-runners", self.workflow)

    def test_latency_uses_main_matrix(self):
        self.assertIn(
            "gateway: ${{ fromJson(needs.prepare-matrix.outputs.gateways) }}",
            self.workflow,
        )

    def test_matrix_built_by_script(self):
        self.assertIn("run: python3 k6/build-matrix.py", self.workflow)

    def test_prepare_matrix_checks_out_repo_first(self):
        # prepare-matrix runs k6/build-matrix.py from the repo, so it must
        # check out the repository before executing the script. A fresh
        # ubuntu-latest runner has no checkout otherwise and matrix
        # preparation fails.
        start = self.workflow.index("prepare-matrix:")
        end = self.workflow.index("build-subgraphs:", start)
        section = self.workflow[start:end]
        self.assertIn("actions/checkout", section)
        self.assertIn("k6/build-matrix.py", section)
        self.assertLess(
            section.index("actions/checkout"),
            section.index("k6/build-matrix.py"),
        )

    def test_jobs_check_out_the_run_commit(self):
        # Results must be generated by the code and config of the run's commit.
        # Checking out the branch by name picks up commits that landed while the
        # run was in progress (run #422 failed after Fusion .NET 10 variants were
        # removed from k6/benchmark-config.json mid-run).
        self.assertNotIn("github.ref_name", self.workflow)
        self.assertNotIn("git push", self.workflow)
        self.assertNotIn("git commit", self.workflow)

    def test_results_published_through_results_branch_worktree(self):
        for job, next_job in [
            ("generate-results-constant:", "generate-results-burst:"),
            ("generate-results-burst:", "generate-results-constant-latency:"),
            ("generate-results-constant-latency:", "generate-results-json:"),
            ("generate-results-json:", "benchmark-summary:"),
            ("benchmark-summary:", "publish-history:"),
        ]:
            start = self.workflow.index(job)
            section = self.workflow[start:self.workflow.index(next_job, start)]
            self.assertIn("results-branch.sh checkout results-branch", section, job)
            self.assertIn("results-branch.sh push results-branch", section, job)
        history = self.workflow[self.workflow.index("publish-history:"):]
        self.assertIn("results-branch.sh checkout results-branch", history)
        self.assertIn("results-branch.sh push results-branch", history)

    def test_benchmark_summary_depends_on_prepare_matrix(self):
        # benchmark-summary gates on needs.prepare-matrix.outputs.should_publish,
        # and GitHub only exposes outputs of direct dependencies — so
        # prepare-matrix must be in its needs list or the condition can never
        # resolve and latest-result publishing/cleanup never runs.
        start = self.workflow.index("benchmark-summary:")
        section = self.workflow[start:]
        self.assertIn(
            "needs.prepare-matrix.outputs.should_publish",
            section,
        )
        needs_start = section.index("needs:")
        needs_end = section.index("if:", needs_start)
        needs_block = section[needs_start:needs_end]
        self.assertIn("prepare-matrix", needs_block)

    def test_publish_history_requires_every_result_job(self):
        jobs = re.findall(r"^  ((?:benchmark|generate-results)-[a-z-]+):$", self.workflow, re.M)
        self.assertIn("generate-results-json", jobs)
        self.assertIn("benchmark-summary", jobs)
        section = self.workflow[self.workflow.index("\n  publish-history:\n"):]
        section = re.split(r"\n  [a-z-]+:\n", section[1:])[0]
        needs = re.findall(r"^      - ([a-z-]+)$", section, re.M)
        condition = re.search(r"^    if: (.*)$", section, re.M).group(1)
        self.assertIn("github.event_name == 'schedule'", condition)
        for job in jobs:
            self.assertIn(job, needs)
            self.assertIn(f"needs.{job}.result == 'success'", condition)

    def test_no_undefined_run_started_at_context(self):
        # github.run_started_at is not a defined GitHub context property
        # (actionlint); timestamps are captured with shell date instead.
        self.assertNotIn("github.run_started_at", self.workflow)
        self.assertNotIn("run_started_at", self.workflow)

    def test_timestamps_captured_via_shell_date(self):
        self.assertIn("started_utc=$(date -u", self.workflow)
        # Line 916-equivalent summary timestamp is generated at summary time,
        # so it must not be labeled "Started".
        self.assertIn("Summary generated (UTC): **$(date -u", self.workflow)

    def test_fusion_version_input_exists(self):
        self.assertIn("fusion_version:", self.workflow)
        # The input documents its Fusion-only scope and that other
        # gateways ignore it (so pinned full-matrix runs keep working).
        self.assertIn("Fusion-family", self.workflow)
        self.assertIn("Non-fusion gateways ignore this input", self.workflow)

    def test_fusion_version_plumbing(self):
        # workflow input -> prepare-matrix env -> build-matrix.py.
        self.assertIn(
            "FUSION_VERSION: ${{ inputs.fusion_version", self.workflow
        )
        # Per-entry version field -> build-gateways env.
        self.assertIn("matrix.gateway.version", self.workflow)
        self.assertIn("BENCH_GATEWAY_VERSION", self.workflow)

    def test_fusion_aot_plumbing(self):
        # Matrix aot field -> build-gateways env -> install.sh axis.
        self.assertIn("matrix.gateway.aot", self.workflow)
        self.assertIn("BENCH_GATEWAY_AOT", self.workflow)

    def test_runtime_benchmark_steps_forward_aot_flag(self):
        # start.sh defaults a missing BENCH_GATEWAY_AOT to JIT ("0"), so
        # every runtime "Run benchmark" step must forward matrix.gateway.aot;
        # otherwise a built AOT artifact would be launched (or fail to
        # launch) as JIT at measure time.
        blocks = self.workflow.split("- name: Run benchmark")
        # Exactly the constant, burst and constant-latency runtime steps.
        self.assertEqual(len(blocks), 4)
        for block in blocks[1:]:
            env_block = block.split("run: ./k6/benchmark.sh", 1)[1].split(
                "USE_PREBUILT_GATEWAY:", 1
            )[0]
            self.assertIn("BENCH_GATEWAY_AOT", env_block)
            self.assertIn("matrix.gateway.aot", env_block)


